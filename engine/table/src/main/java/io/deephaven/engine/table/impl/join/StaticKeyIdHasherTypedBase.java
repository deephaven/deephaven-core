package io.deephaven.engine.table.impl.join;

import io.deephaven.engine.table.ColumnSource;
import io.deephaven.engine.table.impl.by.typed.TypedHasherFactory;
import org.jetbrains.annotations.NotNull;

import static io.deephaven.engine.table.impl.JoinControl.MAX_TABLE_SIZE;

/**
 * A {@link KeyIdHasher} for a set of keys that is built once and then only probed. It only adds keys; the ids are
 * handed out in insertion order, and the table doubles by a full rehash as soon as an insertion takes it past its load
 * factor, so a table sized for its keys never grows.
 * <p>
 * The typed implementations are generated by {@link TypedHasherFactory}; {@link #make} returns one suitable for the key
 * sources.
 */
public abstract class StaticKeyIdHasherTypedBase extends KeyIdHasher {

    // the most keys the table holds before it doubles
    private long maximumEntries;

    // whether the keys are complete, so that a build is a mistake
    private boolean complete = false;

    protected StaticKeyIdHasherTypedBase(ColumnSource<?>[] tableKeySources, int tableSize, double maximumLoadFactor) {
        super(tableKeySources, tableSize, maximumLoadFactor);
        maximumEntries = maximumEntries(tableSize);
    }

    /**
     * Make a hasher for keys with the types of {@code tableKeySources}.
     *
     * @param tableKeySources sources with the key types; every source later built or probed must have the same chunk
     *        types
     * @param tableSize the initial number of slots, a power of two
     * @param maximumLoadFactor the fraction of the slots that may be occupied before the table grows
     * @return a hasher with no keys
     */
    public static StaticKeyIdHasherTypedBase make(
            @NotNull final ColumnSource<?>[] tableKeySources,
            final int tableSize,
            final double maximumLoadFactor) {
        return TypedHasherFactory.make(StaticKeyIdHasherTypedBase.class, tableKeySources, tableKeySources, tableSize,
                maximumLoadFactor, maximumLoadFactor);
    }

    /**
     * Declare the keys complete: from now on the table is only probed, and a build that is given any rows throws.
     * Completing is optional; it guards against building by mistake, and changes nothing else.
     */
    public void complete() {
        complete = true;
    }

    @Override
    public long size() {
        return numEntries;
    }

    @Override
    protected void prepareForChunk(final Context context, final int nextChunkSize) {
        if (complete) {
            throw new IllegalStateException("The keys are complete, so the hasher may only be probed");
        }
    }

    /**
     * Called by the generated build after each insertion: double the table once it holds more keys than its load factor
     * allows, before the next key is probed. A rehash does not change the ids, so the build carries on with the next
     * row.
     */
    protected final void growIfFull() {
        if (numEntries > maximumEntries) {
            grow();
        }
    }

    private void grow() {
        final int oldSize = tableSize;
        if (oldSize >= MAX_TABLE_SIZE) {
            throw new UnsupportedOperationException("Hash table exceeds maximum size!");
        }
        tableSize = oldSize * 2;
        maximumEntries = maximumEntries(tableSize);
        rehashInternalFull(oldSize);
    }

    private long maximumEntries(final int tableSize) {
        return (long) (tableSize * maximumLoadFactor);
    }

    @Override
    protected int allocateId(final int slot) {
        return nextId++;
    }
}
