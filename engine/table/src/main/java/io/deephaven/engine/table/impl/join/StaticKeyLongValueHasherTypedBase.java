package io.deephaven.engine.table.impl.join;

import io.deephaven.base.verify.Require;
import io.deephaven.chunk.Chunk;
import io.deephaven.chunk.LongChunk;
import io.deephaven.chunk.WritableLongChunk;
import io.deephaven.chunk.attributes.Any;
import io.deephaven.chunk.attributes.Values;
import io.deephaven.engine.rowset.RowSequence;
import io.deephaven.engine.table.ColumnSource;
import io.deephaven.engine.table.WritableColumnSource;
import io.deephaven.engine.table.impl.by.typed.TypedHasherFactory;
import io.deephaven.engine.table.impl.sources.InMemoryColumnSource;
import io.deephaven.engine.table.impl.sources.immutable.ImmutableLongArraySource;
import io.deephaven.engine.table.impl.util.TypedHasherUtil.BuildOrProbeContext;
import io.deephaven.util.QueryConstants;
import org.jetbrains.annotations.NotNull;

import static io.deephaven.engine.table.impl.JoinControl.CHUNK_SIZE;
import static io.deephaven.engine.table.impl.JoinControl.MAX_TABLE_SIZE;
import static io.deephaven.engine.table.impl.util.TypedHasherUtil.getKeyChunks;
import static io.deephaven.engine.table.impl.util.TypedHasherUtil.getPrevKeyChunks;

/**
 * An open-addressed hash table that maps each distinct key to a {@code long} value, for a set of keys that is built
 * once and then only probed.
 * <p>
 * The value lives in its key's slot, so a probe reads it from the slot it finds the key in, with no further load. That
 * suits a caller whose only per-key state is one {@code long} that every probe reads. A {@link KeyIdHasher} suits state
 * that is larger, or that changes: it gives each key a dense id that its caller indexes its own state by.
 * <p>
 * A build gives each new key the value of its row; what it does with the value of a key that is already in the table is
 * set by the hasher's {@link RepeatedKey}. The table doubles by a full rehash as soon as an insertion takes it past its
 * load factor, so a table sized for its keys never grows.
 * <p>
 * The typed implementations are generated by {@link TypedHasherFactory}; {@link #make} returns one suitable for the key
 * sources.
 */
public abstract class StaticKeyLongValueHasherTypedBase {

    /**
     * What a build does with the value of a key that is already in the table.
     */
    public enum RepeatedKey {
        /** Keep the value from the key's first row. */
        KEEP_FIRST,
        /** Replace the value with that of the key's latest row. */
        KEEP_LAST,
        /** Replace the value with the hasher's mark value, and remember that a key was {@link #anyMarked() marked}. */
        MARK
    }

    /**
     * Receives the values for one chunk of probed rows.
     */
    @FunctionalInterface
    public interface ValueChunkConsumer {
        /**
         * @param rows the rows of this chunk
         * @param values the value of each row's key, or the missing value for a key that is not in the table, parallel
         *        to {@code rows}
         */
        void accept(RowSequence rows, LongChunk<Values> values);
    }

    /** The value of a slot that holds no key, which a build may not store. */
    protected static final long EMPTY_VALUE = QueryConstants.NULL_LONG;

    // the number of slots in our table
    protected int tableSize;

    /** How many slots of the table are occupied? */
    protected long numEntries = 0;

    protected final double maximumLoadFactor;

    // the keys for our hash entries
    protected final WritableColumnSource[] mainKeySources;

    // the value of the key in each slot, or EMPTY_VALUE
    protected final ImmutableLongArraySource mainValue = new ImmutableLongArraySource();

    // the most keys the table holds before it doubles
    private long maximumEntries;

    private RepeatedKey repeatedKey;
    private long markValue;
    // whether a build has stored the mark value
    private boolean anyMarked = false;

    // whether the keys are complete, so that a build is a mistake
    private boolean complete = false;

    protected StaticKeyLongValueHasherTypedBase(ColumnSource<?>[] tableKeySources, int tableSize,
            double maximumLoadFactor) {
        this.tableSize = tableSize;
        Require.leq(tableSize, "tableSize", MAX_TABLE_SIZE);
        Require.gtZero(tableSize, "tableSize");
        Require.eq(Integer.bitCount(tableSize), "Integer.bitCount(tableSize)", 1);
        Require.gtZero(maximumLoadFactor, "maximumLoadFactor");
        Require.leq(maximumLoadFactor, "maximumLoadFactor", 0.95);
        this.maximumLoadFactor = maximumLoadFactor;
        maximumEntries = maximumEntries(tableSize);

        mainKeySources = new WritableColumnSource[tableKeySources.length];
        for (int ii = 0; ii < tableKeySources.length; ++ii) {
            mainKeySources[ii] = InMemoryColumnSource.getImmutableMemoryColumnSource(tableSize,
                    tableKeySources[ii].getType(), tableKeySources[ii].getComponentType());
        }
        // a new array is filled with NULL_LONG, which is EMPTY_VALUE
        mainValue.ensureCapacity(tableSize);
    }

    /**
     * Make a hasher for keys with the types of {@code tableKeySources}.
     *
     * @param tableKeySources sources with the key types; every source later built or probed must have the same chunk
     *        types
     * @param tableSize the initial number of slots, a power of two
     * @param maximumLoadFactor the fraction of the slots that may be occupied before the table grows
     * @param repeatedKey what a build does with the value of a key that is already in the table
     * @param markValue the value that {@link RepeatedKey#MARK} stores; it may not be {@link QueryConstants#NULL_LONG}
     * @return a hasher with no keys
     */
    public static StaticKeyLongValueHasherTypedBase make(
            @NotNull final ColumnSource<?>[] tableKeySources,
            final int tableSize,
            final double maximumLoadFactor,
            @NotNull final RepeatedKey repeatedKey,
            final long markValue) {
        Require.neq(markValue, "markValue", EMPTY_VALUE, "EMPTY_VALUE");
        final StaticKeyLongValueHasherTypedBase hasher = TypedHasherFactory.make(
                StaticKeyLongValueHasherTypedBase.class, tableKeySources, tableKeySources, tableSize,
                maximumLoadFactor, maximumLoadFactor);
        hasher.repeatedKey = repeatedKey;
        hasher.markValue = markValue;
        return hasher;
    }

    /**
     * Build the keys in {@code keyChunks}, adding the keys that are not yet in the table.
     *
     * @param keyChunks one chunk per key column, all the same size
     * @param values the value of each row, parallel to {@code keyChunks}; none may be {@link QueryConstants#NULL_LONG}
     */
    public void build(@NotNull final Chunk<? extends Values>[] keyChunks,
            @NotNull final LongChunk<? extends Any> values) {
        if (keyChunks[0].size() == 0) {
            return;
        }
        if (complete) {
            throw new IllegalStateException("The keys are complete, so the hasher may only be probed");
        }
        buildChunk(keyChunks, values);
    }

    /**
     * Build the keys of {@code rows}, giving each new key the row key of its row as its value.
     *
     * @param rows the rows to build
     * @param sources the key sources
     */
    public void build(@NotNull final RowSequence rows, @NotNull final ColumnSource<?>[] sources) {
        if (rows.isEmpty()) {
            return;
        }
        final int chunkSize = (int) Math.min(CHUNK_SIZE, rows.size());
        try (final BuildOrProbeContext bc = new BuildOrProbeContext(sources, chunkSize);
                final RowSequence.Iterator rsIt = rows.getRowSequenceIterator()) {
            // noinspection unchecked
            final Chunk<Values>[] keyChunks = new Chunk[sources.length];
            while (rsIt.hasMore()) {
                final RowSequence chunkOk = rsIt.getNextRowSequenceWithLength(chunkSize);
                getKeyChunks(sources, bc.getContexts, keyChunks, chunkOk);
                build(keyChunks, chunkOk.asRowKeyChunk());
                bc.resetSharedContexts();
            }
        }
    }

    /**
     * Find the value of each key in {@code keyChunks}.
     *
     * @param keyChunks one chunk per key column, all the same size
     * @param values receives the value of each row's key, or {@code missingValue} for a key that is not in the table;
     *        its capacity must be at least the size of the key chunks
     * @param missingValue the value for a key that is not in the table
     */
    public void probe(@NotNull final Chunk<? extends Values>[] keyChunks,
            @NotNull final WritableLongChunk<Values> values, final long missingValue) {
        final int size = keyChunks[0].size();
        values.setSize(size);
        if (size == 0) {
            return;
        }
        probeChunk(keyChunks, values, missingValue);
    }

    /**
     * Find the value of each row's key.
     *
     * @param rows the rows to probe
     * @param sources the key sources
     * @param usePrev whether to read the previous values of {@code sources}
     * @param missingValue the value for a key that is not in the table
     * @param consumer receives the values, one chunk of rows at a time
     */
    public void probe(
            @NotNull final RowSequence rows,
            @NotNull final ColumnSource<?>[] sources,
            final boolean usePrev,
            final long missingValue,
            @NotNull final ValueChunkConsumer consumer) {
        if (rows.isEmpty()) {
            return;
        }
        final int chunkSize = (int) Math.min(CHUNK_SIZE, rows.size());
        try (final BuildOrProbeContext bc = new BuildOrProbeContext(sources, chunkSize);
                final RowSequence.Iterator rsIt = rows.getRowSequenceIterator();
                final WritableLongChunk<Values> values = WritableLongChunk.makeWritableChunk(chunkSize)) {
            // noinspection unchecked
            final Chunk<Values>[] keyChunks = new Chunk[sources.length];
            while (rsIt.hasMore()) {
                final RowSequence chunkOk = rsIt.getNextRowSequenceWithLength(chunkSize);
                if (usePrev) {
                    getPrevKeyChunks(sources, bc.getContexts, keyChunks, chunkOk);
                } else {
                    getKeyChunks(sources, bc.getContexts, keyChunks, chunkOk);
                }
                probe(keyChunks, values, missingValue);
                consumer.accept(chunkOk, values);
                bc.resetSharedContexts();
            }
        }
    }

    /**
     * Declare the keys complete: from now on the table is only probed, and a build that is given any rows throws.
     * Completing is optional; it guards against building by mistake, and changes nothing else.
     */
    public void complete() {
        complete = true;
    }

    /**
     * @return whether a build has given any key the mark value, which only {@link RepeatedKey#MARK} does
     */
    public boolean anyMarked() {
        return anyMarked;
    }

    /**
     * @return the number of keys in the table
     */
    public long size() {
        return numEntries;
    }

    /**
     * Called by the generated build for a key that is already in the table.
     *
     * @param existing the key's value
     * @param incoming the value of the row being built
     * @return the key's new value
     */
    protected final long repeatedValue(final long existing, final long incoming) {
        switch (repeatedKey) {
            case KEEP_FIRST:
                return existing;
            case KEEP_LAST:
                return incoming;
            default:
                anyMarked = true;
                return markValue;
        }
    }

    /**
     * Called by the generated build after each insertion: double the table once it holds more keys than its load factor
     * allows, before the next key is probed.
     */
    protected final void growIfFull() {
        if (numEntries > maximumEntries) {
            grow();
        }
    }

    private void grow() {
        final int oldSize = tableSize;
        if (oldSize >= MAX_TABLE_SIZE) {
            throw new UnsupportedOperationException("Hash table exceeds maximum size!");
        }
        tableSize = oldSize * 2;
        maximumEntries = maximumEntries(tableSize);
        rehashInternalFull(oldSize);
    }

    private long maximumEntries(final int tableSize) {
        return (long) (tableSize * maximumLoadFactor);
    }

    protected int hashToTableLocation(final int hash) {
        return hash & (tableSize - 1);
    }

    protected abstract void buildChunk(Chunk[] sourceKeyChunks, LongChunk<? extends Any> values);

    protected abstract void probeChunk(Chunk[] sourceKeyChunks, WritableLongChunk<Values> values, long missingValue);

    protected abstract void rehashInternalFull(int oldSize);
}
