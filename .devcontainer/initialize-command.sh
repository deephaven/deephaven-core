#!/bin/bash
# devc host-side init (devcontainer "initializeCommand"). Runs on the HOST,
# before the container is created — the only lifecycle hook that does.
set -e
mkdir -p "$HOME/.config/devc/.claude"

# Git identity for the container. ~/.gitconfig is container-local and wiped on every
# rebuild, so the container has no idea who you are. Rather than bind the whole host
# ~/.gitconfig — which would drag in host-absolute paths, credential helpers, and
# signing config that don't work in here — extract an explicit allowlist. Only the
# keys below cross the boundary.
#
# Always written (even when the host has no identity configured) so the bind-mount source
# exists. `git config --file` does the writing rather than `echo`, so a value containing
# `#`, `;`, `"` or `\` is quoted the way git's own parser expects to read it back.
identity="$HOME/.config/devc/gitconfig-identity"
printf '%s\n' "# Generated by devc initialize-command.sh — do not edit." > "$identity"
name="$(git config --get user.name || true)"
email="$(git config --get user.email || true)"
[ -n "$name" ] && git config --file "$identity" user.name "$name"
[ -n "$email" ] && git config --file "$identity" user.email "$email"

# No devc-bridge setup here, deliberately. The bridge is an opt-in add-on, and devc does not
# create its directories on hosts that may never use it. Its mount sources are made by the
# host bridge itself (`devc-bridge start` seeds ~/.config/devc-bridge/), which is the
# documented prerequisite for opting in — see features/devc-bridge/README.md.

# Explicit, because the git-identity tests above are the last thing that can set $?: an unset
# name or email leaves the final `[ -n ... ]` failing, and a non-zero initializeCommand aborts
# container creation. A host with no git identity is a warning (from the git-container-config
# Feature's post-create.sh), not a failure.
exit 0
